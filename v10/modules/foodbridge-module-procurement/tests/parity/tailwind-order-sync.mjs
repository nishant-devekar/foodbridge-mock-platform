#!/usr/bin/env node
/*
  node tailwind-order-sync.mjs

  Copies the ORDER of production's Tailwind utilities into js/vendor/tailwind-order.js.

  Two utilities of the same plugin (bg-blue-500 and bg-green-600 on one button) resolve by which
  rule comes later, and Tailwind emits same-plugin rules in the order it first met each class.
  Production's build meets them file by file (its content globs); the prototype's Tailwind (the
  play CDN) meets them in the DOM. So the prototype puts production's order in the DOM first: a
  hidden element carrying every class of production's stylesheet, in production's order — the
  first thing in <body>, before anything renders.
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { startServers, NOW } from './lib/servers.mjs';
import { openSide, settle, warmStorage } from './lib/capture.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FILE = path.join(HERE, '../../js/vendor/tailwind-order.js');
const servers = await startServers();
const browser = await chromium.launch();
try {
  await servers.scenario({ list: 'normal', reset: true });
  const { page } = await openSide(browser, 'react', { url: servers.reactUrl, viewport: 'desktop', now: NOW, storage: await warmStorage(await servers.setup()) });
  await settle(page, { expect: 'list' });
  const classes = await page.evaluate(() => {
    // Tailwind's own sheet: the one that defines its preflight reset and the most utilities.
    let best = null;
    for (const sheet of document.styleSheets) {
      let rules; try { rules = sheet.cssRules; } catch { continue; }
      const text = [...rules].slice(0, 400).map((r) => r.cssText).join('\n');
      if (!/--tw-/.test(text)) continue;
      if (!best || rules.length > best.cssRules.length) best = sheet;
    }
    const out = [];
    const seen = new Set();
    const walk = (rules) => {
      for (const r of rules) {
        if (r.cssRules && !r.selectorText) { walk(r.cssRules); continue; }
        if (!r.selectorText) continue;
        for (const m of r.selectorText.matchAll(/\.((?:\\.|[\w-])+)/g)) {
          const cls = m[1].replace(/\\(.)/g, '$1');
          if (!seen.has(cls)) { seen.add(cls); out.push(cls); }
        }
      }
    };
    if (best) walk(best.cssRules);
    return out;
  });
  const body = `/*
  Production's Tailwind utilities, in the order its stylesheet emits them, put in the DOM before
  anything else so the play CDN meets them in that order. Generated by
  tests/parity/tailwind-order-sync.mjs — do not edit. Why: see that script's header.
*/
(() => {
  const el = document.createElement('div');
  el.hidden = true;
  // Its own classes include display utilities (flex, grid…) that would beat [hidden].
  el.style.setProperty('display', 'none', 'important');
  el.setAttribute('aria-hidden', 'true');
  el.setAttribute('data-tailwind-order', '');
  el.className = ${JSON.stringify(classes.join(' '))};
  document.body.prepend(el);
})();
`;
  fs.writeFileSync(FILE, body);
  console.log(`${classes.length} classes → ${path.relative(process.cwd(), FILE)}`);
} finally {
  await browser.close();
  await servers.stop();
}
